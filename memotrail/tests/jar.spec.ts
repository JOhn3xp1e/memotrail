import { test, expect } from "./fixtures";

test("jar handles empty, single, favorites, non-repeating picks and offline details", async ({ page, context }) => {
  await page.goto("/");
  await page.getByRole("link", { name: "Pick a memory", exact: true }).click();
  await expect(page).toHaveURL(/\/jar$/);
  await expect(page.getByRole("heading", { name: "Good things start with one memory." })).toBeVisible();
  await expect(page.getByRole("button", { name: "Shake the Jar" })).toBeDisabled();
  const editor = await context.newPage();
  await editor.goto("/add");
  await editor.getByLabel("Give this moment a title").fill("A quiet afternoon");
  await editor.getByLabel("What made it special?").fill("A long conversation.");
  await editor.getByRole("button", { name: "Save memory", exact: true }).click();
  await expect(editor).toHaveURL(/\/timeline$/);
  await page.bringToFront();
  await expect(page.getByRole("button", { name: "Shake the Jar" })).toBeEnabled();
  await page.getByRole("button", { name: "Shake the Jar" }).click();
  await expect(page.locator(".jar-reveal-card h2")).toHaveText("A quiet afternoon");
  await expect(page.locator(".jar-word-memory")).toBeVisible();
  await page.getByRole("button", { name: "Pick Another" }).click();
  await expect(page.locator(".jar-reveal-card h2")).toHaveText("A quiet afternoon");
  await page.getByRole("switch", { name: "Favorites Only" }).click();
  await expect(page.getByRole("heading", { name: "Your favorites belong here." })).toBeVisible();
  await editor.getByRole("button", { name: "Favorite memory: A quiet afternoon", exact: true }).click();
  await page.bringToFront();
  await expect(page.getByRole("button", { name: "Pick a memory from the jar" })).toBeEnabled();
  await page.getByRole("button", { name: "Pick a memory from the jar" }).focus();
  await page.keyboard.press("Enter");
  await expect(page.locator(".jar-reveal-card h2")).toHaveText("A quiet afternoon");
  await page.getByRole("switch", { name: "Favorites Only" }).click();
  await editor.goto("/add");
  await editor.getByLabel("Give this moment a title").fill("By the lake");
  await editor.locator("input[type=file]").setInputFiles("public/photos/lake-weekend.jpg");
  await editor.getByRole("button", { name: "Save memory", exact: true }).click();
  await expect(editor).toHaveURL(/\/timeline$/);
  await expect(page.locator(".jar-count")).toContainText("2 memories");
  await page.getByRole("button", { name: "Shake the Jar" }).click();
  await expect(page.locator(".jar-reveal-card h2")).toHaveText("By the lake");
  await expect(page.locator(".jar-reveal-card > img")).toHaveAttribute("src", /^blob:/);
  await page.getByRole("button", { name: "Pick Another" }).click();
  await expect(page.locator(".jar-reveal-card h2")).toHaveText("A quiet afternoon");
  await page.getByRole("button", { name: "Pick Another" }).click();
  await expect(page.locator(".jar-reveal-card h2")).toHaveText("By the lake");
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Switch to dark theme" }).click();
  await page.screenshot({ path: "artifacts/jar-dark-mobile.png", fullPage: true });
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload();
  await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true);
  await context.setOffline(true);
  await page.reload();
  await page.getByRole("button", { name: "Shake the Jar" }).click();
  const title = await page.locator(".jar-reveal-card h2").innerText();
  await page.getByRole("link", { name: "Open Memory" }).click();
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(title);
});

test("jar completes shake and paper animation with motion enabled", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.goto("/add");
  await page.getByLabel("Give this moment a title").fill("An animated keepsake");
  await page.getByRole("button", { name: "Save memory", exact: true }).click();
  await expect(page).toHaveURL(/\/timeline$/);
  await page.goto("/jar");
  await page.getByRole("button", { name: "Shake the Jar" }).click();
  await expect(page.locator(".jar-reveal-card h2")).toHaveText("An animated keepsake");
  await expect(page.getByRole("button", { name: "Shake the Jar" })).toBeEnabled();
});
